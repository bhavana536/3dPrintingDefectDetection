def _collect_predictions(model, gen, n_samples):
    """Run inference over the full generator, return (y_true, y_prob)."""
    gen.reset()
    y_true_list, y_prob_list = [], []
    for _ in range(len(gen)):
        X, y = next(gen)
        y_prob_list.append(model.predict(X, verbose=0))
        y_true_list.extend(np.argmax(y, axis=1).tolist())
    y_prob  = np.vstack(y_prob_list)[:n_samples]
    y_true  = np.array(y_true_list[:n_samples])
    return y_true, y_prob


