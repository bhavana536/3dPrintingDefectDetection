def build_generators(dataset_dir: str):
    """
    Returns (train_gen, val_gen, test_gen).
    Images are loaded as GRAYSCALE 128×128, normalised to [0,1].
    Split: 80 % train / 10 % val / 10 % test.
    """
    shape      = (cfg.IMG_HEIGHT, cfg.IMG_WIDTH)
    color_mode = "grayscale"   # paper §3.2.2: converted to grayscale

    # ── 10 % test slice ───────────────────────────────────────────────────────
    test_gen = ImageDataGenerator(
        rescale=1.0 / 255,
        validation_split=cfg.TEST_SPLIT,
    ).flow_from_directory(
        dataset_dir, target_size=shape, color_mode=color_mode,
        batch_size=cfg.BATCH_SIZE, class_mode="categorical",
        subset="validation", shuffle=False, seed=SEED,
    )

    # ── 80 / 10 train / val from remaining 90 % ───────────────────────────────
    val_frac = cfg.VAL_SPLIT / (1.0 - cfg.TEST_SPLIT)   # ≈ 0.1111

    tv = ImageDataGenerator(
        rescale=1.0 / 255,
        validation_split=val_frac,
        # Mild augmentation consistent with the paper
        horizontal_flip=True,
        rotation_range=10,
        zoom_range=0.10,
    )
    train_gen = tv.flow_from_directory(
        dataset_dir, target_size=shape, color_mode=color_mode,
        batch_size=cfg.BATCH_SIZE, class_mode="categorical",
        subset="training", shuffle=True, seed=SEED,
    )
    val_gen = tv.flow_from_directory(
        dataset_dir, target_size=shape, color_mode=color_mode,
        batch_size=cfg.BATCH_SIZE, class_mode="categorical",
        subset="validation", shuffle=False, seed=SEED,
    )

    print(f"\n  Train : {train_gen.n:,} images  ({len(train_gen)} batches)")
    print(f"  Val   : {val_gen.n:,}   images  ({len(val_gen)} batches)")
    print(f"  Test  : {test_gen.n:,}  images  ({len(test_gen)} batches)")
    print(f"  Class indices : {train_gen.class_indices}")

    return train_gen, val_gen, test_gen


# ─────────────────────────────────────────────────────────────────────────────
# 6.  MLSA BLOCK  (paper Fig. 9 & §3.3.2)
#
#  Architecture:
#    Input x (H×W×C)
#      │
#      ├─ Conv3×3 dr=3 ──┐
#      │                  Add ──→ Multiply(sigmoid_gate_A) ──┐
#      └─ Conv3×3 (plain)─┘                                  │
#                                                            Add ──→ Multiply(sigmoid_gate_B) ──→ Concat ──→ Conv1×1 ──→ Add(skip) → output
#      ├─ Conv3×3 dr=2 ──┐                                   │                                   ↑
#      │                  Add ──→ sigmoid_gate_B ────────────┘       Conv3×3 (main path) ─────────┘
#      └─ Conv3×3 dr=1 ──┘
#
#  Key design choices (paper §3.3.2):
#    - Multi-dilation captures defect-specific features at multiple spatial scales
#    - Stringing = fine filament-level (small receptive field, dr=1)
#    - Warping / Cracking = broader deformation (large receptive field, dr=3)
#    - Sigmoid gates suppress non-informative background regions
#    - Skip connection preserves input information
# ─────────────────────────────────────────────────────────────────────────────

def mlsa_block(x, C: int, block_id: int) -> tf.Tensor:
    """
    Multi-Level Spatial Attention (MLSA) block.

    Args:
        x        : input feature map  (H, W, C_in)
        C        : number of output filters
        block_id : integer used for unique layer naming

    Returns:
        output feature map (H, W, C)
    """
    bid = block_id   # short alias for naming

    # ── Branch 1: three dilated convolutions (multi-scale) ───────────────────
    d1 = layers.Conv2D(C, 3, padding="same",
                       dilation_rate=cfg.DILATION_RATES[0],   # dr=1
                       activation="relu",
                       name=f"mlsa{bid}_d1")(x)

    d2 = layers.Conv2D(C, 3, padding="same",
                       dilation_rate=cfg.DILATION_RATES[1],   # dr=2
                       activation="relu",
                       name=f"mlsa{bid}_d2")(x)

    d3 = layers.Conv2D(C, 3, padding="same",
                       dilation_rate=cfg.DILATION_RATES[2],   # dr=3
                       activation="relu",
                       name=f"mlsa{bid}_d3")(x)

    # ── Attention gate A: (d3 + plain) * sigmoid ─────────────────────────────
    plain = layers.Conv2D(C, 3, padding="same", activation="relu",
                          name=f"mlsa{bid}_plain")(x)

    add_d3_plain = layers.Add(name=f"mlsa{bid}_add_d3_plain")([d3, plain])

    gate_A = layers.Conv2D(C, 1, padding="same", activation="sigmoid",
                           name=f"mlsa{bid}_gateA")(add_d3_plain)

    attn_A = layers.Multiply(name=f"mlsa{bid}_attnA")([add_d3_plain, gate_A])

    # ── Attention gate B: attn_A + (d1 + d2) * sigmoid ───────────────────────
    add_d1d2 = layers.Add(name=f"mlsa{bid}_add_d1d2")([d1, d2])

    gate_B = layers.Conv2D(C, 1, padding="same", activation="sigmoid",
                           name=f"mlsa{bid}_gateB")(add_d1d2)

    attn_B = layers.Multiply(name=f"mlsa{bid}_attnB")([attn_A, gate_B])

    # ── Main path (plain 3×3 conv) ────────────────────────────────────────────
    main = layers.Conv2D(C, 3, padding="same", activation="relu",
                         name=f"mlsa{bid}_main")(x)

    # ── Concatenate attention output + main path, project to C filters ────────
    concat = layers.Concatenate(name=f"mlsa{bid}_concat")([attn_B, main])
    proj   = layers.Conv2D(C, 1, padding="same", activation="relu",
                           name=f"mlsa{bid}_proj")(concat)

    # ── Skip connection: project input to C channels if needed ───────────────
    if x.shape[-1] != C:
        x = layers.Conv2D(C, 1, padding="same",
                          name=f"mlsa{bid}_skip_proj")(x)

    out = layers.Add(name=f"mlsa{bid}_out")([proj, x])
    return out


# ─────────────────────────────────────────────────────────────────────────────
# 7.  FULL MLSA-CNN ARCHITECTURE  (paper Fig. 8 & §3.3.2, Table 4)
#
#  Input (128×128×1, grayscale)
#    │
#    └─ Conv5×5 (C=16) + BN
#         │
#         ├─ Level 1: Conv5×5(16) → Conv3×3(16) → BN → MLSA(16) → BN → GAP → Dense(256,ReLU)
#         ├─ Level 2: Conv5×5(32) → Conv3×3(32) → BN → MLSA(32) → BN → GAP → Dense(256,ReLU)
#         ├─ Level 3: Conv5×5(64) → Conv3×3(64) → BN → MLSA(64) → BN → GAP → Dense(256,ReLU)
#         ├─ Level 4: Conv5×5(128)→ Conv3×3(128)→ BN → MLSA(128)→ BN → GAP → Dense(256,ReLU)
#         └─ Level 5: Conv5×5(256)→ Conv3×3(256)→ BN → MLSA(256)→ BN → GAP → Dense(256,ReLU)
#              │
#              Add (aggregate all 5 level embeddings)
#              │
#              Dense(256, ReLU) → Dropout(0.3)
#              Dense(128, ReLU) → Dropout(0.3)
#              Dense(4,   Softmax)
# ─────────────────────────────────────────────────────────────────────────────

def build_mlsa_cnn(num_classes: int = 4) -> Model:
    """
    Builds the paper's custom MLSA-CNN (Table 4 / Fig. 8).

    Paper §3.3.2:
      - Grayscale input 128×128×1
      - Initial Conv 5×5 (16 filters) + BN
      - 5 levels with progressively increasing filters [16,32,64,128,256]
      - Each level: Conv5×5 → Conv3×3 → BN → MLSA block → BN
                    → Global Average Pooling → Dense(256, ReLU)
      - All 5 level embeddings summed (Add)
      - Dense(256, ReLU) → Dropout(0.3) → Dense(128, ReLU) → Dropout(0.3)
      - Dense(num_classes, Softmax)
    """
    inp = keras.Input(
        shape=(cfg.IMG_HEIGHT, cfg.IMG_WIDTH, cfg.CHANNELS),
        name="input_grayscale",
    )

    # ── Initial convolution (paper: 16 filters, 5×5, same padding, BN) ───────
    x = layers.Conv2D(
        cfg.FILTER_LEVELS[0], (5, 5),
        padding="same", activation="relu",
        name="init_conv",
    )(inp)
    x = layers.BatchNormalization(name="init_bn")(x)

    # ── 5 hierarchical levels ─────────────────────────────────────────────────
    level_embeddings = []

    for i, C in enumerate(cfg.FILTER_LEVELS):
        level = i + 1   # 1-indexed for naming

        # Conv 5×5
        x = layers.Conv2D(
            C, (5, 5), padding="same", activation="relu",
            name=f"conv5_L{level}",
        )(x)

        # Conv 3×3
        x = layers.Conv2D(
            C, (3, 3), padding="same", activation="relu",
            name=f"conv3_L{level}",
        )(x)

        # Batch Normalisation before MLSA
        x = layers.BatchNormalization(name=f"bn_pre_mlsa_L{level}")(x)

        # MLSA block
        x = mlsa_block(x, C, block_id=level)

        # Batch Normalisation after MLSA
        x = layers.BatchNormalization(name=f"bn_post_mlsa_L{level}")(x)

        # Global Average Pooling → Dense(256) per-level embedding
        gap = layers.GlobalAveragePooling2D(name=f"gap_L{level}")(x)
        emb = layers.Dense(256, activation="relu",
                           name=f"emb_L{level}")(gap)
        level_embeddings.append(emb)

    # ── Aggregate all 5 level embeddings by element-wise addition ─────────────
    agg = layers.Add(name="agg_levels")(level_embeddings)

    # ── Dense classification head ─────────────────────────────────────────────
    z = layers.Dense(cfg.DENSE_UNITS[0], activation="relu",
                     name="head_dense_256")(agg)
    z = layers.Dropout(cfg.DROPOUT_RATE, name="dropout_256")(z)

    z = layers.Dense(cfg.DENSE_UNITS[1], activation="relu",
                     name="head_dense_128")(z)
    z = layers.Dropout(cfg.DROPOUT_RATE, name="dropout_128")(z)

    out = layers.Dense(num_classes, activation=cfg.OUT_ACTIVATION,
                       name="output")(z)

    model = Model(inputs=inp, outputs=out, name="MLSA_CNN")
    return model


