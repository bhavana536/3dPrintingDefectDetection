    train_gen, val_gen, test_gen = build_generators(staging_dir)
    class_names = [k for k, _ in sorted(train_gen.class_indices.items(),
                                        key=lambda kv: kv[1])]
    n_classes = len(class_names)
    print(f"\n  Classes : {class_names}")
    print(f"  Input   : {cfg.IMG_HEIGHT}×{cfg.IMG_WIDTH}×{cfg.CHANNELS}  (grayscale)")

