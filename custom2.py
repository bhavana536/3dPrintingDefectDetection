def get_callbacks(ckpt_path: str) -> list:
    return [
        EarlyStopping(
            monitor="val_accuracy",
            patience=cfg.PATIENCE,    # 15
            min_delta=cfg.MIN_DELTA,  # 0.001
            restore_best_weights=True,
            verbose=1,
        ),
        ModelCheckpoint(
            filepath=ckpt_path,
            monitor="val_accuracy",
            save_best_only=True,
            verbose=0,
        ),
    ]


