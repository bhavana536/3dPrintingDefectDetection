def plot_confusion_matrix(cm, class_names, task_name: str, out_dir: str):
    norm = cm.astype(float) / cm.sum(axis=1, keepdims=True)
    sz   = max(6, len(class_names) * 2)
    fig, ax = plt.subplots(figsize=(sz, sz))
    sns.heatmap(
        norm, annot=True, fmt=".2f", cmap="Blues",
        xticklabels=class_names, yticklabels=class_names, ax=ax,
    )
    ax.set_xlabel("Predicted"); ax.set_ylabel("Actual")
    ax.set_title(f"Confusion Matrix — MLSA-CNN ({task_name})")
    plt.tight_layout()
    p = os.path.join(out_dir, f"cm_{task_name}.png")
    plt.savefig(p, dpi=150); plt.close()
    print(f"  [Saved] {p}")


def plot_roc_curves(y_true, y_score, class_names, task_name: str, out_dir: str):
    n      = len(class_names)
    yb     = label_binarize(y_true, classes=list(range(n)))
    colors = plt.cm.tab10.colors
    plt.figure(figsize=(8, 6))
    for i, cls in enumerate(class_names):
        fpr, tpr, _ = roc_curve(yb[:, i], y_score[:, i])
        plt.plot(fpr, tpr, color=colors[i % 10],
                 label=f"{cls} (AUC={auc(fpr,tpr):.4f})")
    plt.plot([0, 1], [0, 1], "k--", lw=1, label="Random (AUC=0.50)")
    plt.xlim([0, 1]); plt.ylim([0, 1.02])
    plt.xlabel("False Positive Rate"); plt.ylabel("True Positive Rate")
    plt.title(f"ROC Curves — MLSA-CNN ({task_name})")
    plt.legend(loc="lower right"); plt.grid(True); plt.tight_layout()
    p = os.path.join(out_dir, f"roc_{task_name}.png")
    plt.savefig(p, dpi=150); plt.close()
    print(f"  [Saved] {p}")


def full_evaluation(
    model, test_gen, class_names, task_name: str, out_dir: str,
) -> float:
    """
    Runs complete evaluation:
      accuracy, classification report, TP/TN/FP/FN per class,
      confusion matrix plot, ROC curve plot.
    Returns accuracy (%).
    """
    print(f"\n{'='*65}")
    print(f"  Evaluation — MLSA-CNN  ({task_name})")
    print(f"{'='*65}")

    y_true, y_prob = _collect_predictions(model, test_gen, test_gen.n)
    y_pred = np.argmax(y_prob, axis=1)

    acc = accuracy_score(y_true, y_pred) * 100
    print(f"\n  Accuracy : {acc:.4f} %")

    print("\n  Classification Report:")
    print(classification_report(y_true, y_pred,
                                target_names=class_names, digits=4))

    cm = confusion_matrix(y_true, y_pred)
    print("  Confusion Matrix (raw counts):")
    print(cm)

    print("\n  Per-class  TP / TN / FP / FN:")
    for i, cls in enumerate(class_names):
        TP = int(cm[i, i])
        FP = int(cm[:, i].sum() - TP)
        FN = int(cm[i, :].sum() - TP)
        TN = int(cm.sum() - TP - FP - FN)
        print(f"    {cls:<18}  TP={TP:4d}  TN={TN:4d}  FP={FP:4d}  FN={FN:4d}")

    # Per-class TP/TN/FP/FN aggregated for macro accuracy (paper Eq. 4)
    n_cls = len(class_names)
    agg_TP = agg_TN = agg_FP = agg_FN = 0
    for i in range(n_cls):
        TP = int(cm[i, i])
        FP = int(cm[:, i].sum() - TP)
        FN = int(cm[i, :].sum() - TP)
        TN = int(cm.sum() - TP - FP - FN)
        agg_TP += TP; agg_TN += TN; agg_FP += FP; agg_FN += FN
    acc_eq4 = (agg_TP + agg_TN) / (agg_TP + agg_TN + agg_FP + agg_FN) * 100
    print(f"\n  Accuracy (paper Eq.4 formula): {acc_eq4:.4f} %")

    plot_confusion_matrix(cm, class_names, task_name, out_dir)
    plot_roc_curves(y_true, y_prob, class_names, task_name, out_dir)

    return acc


