    model = build_mlsa_cnn(num_classes=n_classes)

    # Paper Table 4: Adam, lr=0.001, categorical_crossentropy
    model.compile(
        optimizer=Adam(learning_rate=cfg.LEARNING_RATE),
        loss=cfg.LOSS,
        metrics=["accuracy"],
    )

