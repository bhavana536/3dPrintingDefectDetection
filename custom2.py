# ─────────────────────────────────────────────────────────────────────────────
# 3.  No_Defect GENERATION  (multi-strategy, adaptive per class)
#
#  Problem: Warping defects spread across the entire image, including corners.
#  So corner crops from Warping images still contain warping patterns and
#  fail a strict std filter, producing very few usable crops (only 13/500).
#
#  Solution: a cascade of 4 crop strategies, tried in order per class.
#  Each strategy targets a different image region. For each image, ALL
#  candidate crops from ALL strategies are collected, then the crop with
#  the LOWEST local contrast (= least texture = least defect) is chosen.
#  This maximises background/clean-print content regardless of defect type.
#
#  Strategy cascade (tried in order until n_per_class is reached):
#    Pass 1  — 4 corner crops           (top-left, top-right, bot-left, bot-right)
#    Pass 2  — 4 edge-midpoint crops    (top-centre, bottom-centre, left-mid, right-mid)
#    Pass 3  — 8 quarter-grid crops     (2×2 offset grid avoids dead centre)
#    Pass 4  — random crops             (random positions, last resort)
#
#  For each image, the LEAST-textured crop (lowest std among candidates)
#  that still exceeds MIN_STD_FLOOR is selected.
#  If nothing exceeds MIN_STD_FLOOR even on pass 4, the absolute
#  minimum-std crop is used (floor relaxed so we always make progress).
# ─────────────────────────────────────────────────────────────────────────────

MIN_STD_FLOOR = 3.0    # absolute minimum std to save ANY crop (avoids pure black)


def _candidate_crops(img: Image.Image, crop_size: int, pass_num: int) -> list:
    """
    Return a list of (crop_PIL, x, y) tuples for the given pass.

    pass_num:
      1 → 4 corners
      2 → 4 edge midpoints
      3 → 8 quarter-grid positions
      4 → 16 random positions (seeded by image content for reproducibility)
    """
    w, h = img.size
    if w < crop_size or h < crop_size:
        return []

    def _safe_crop(x, y):
        x = max(0, min(int(x), w - crop_size))
        y = max(0, min(int(y), h - crop_size))
        return img.crop((x, y, x + crop_size, y + crop_size)), x, y

    if pass_num == 1:
        # 4 corners
        positions = [
            (0,            0           ),
            (w - crop_size, 0           ),
            (0,            h - crop_size),
            (w - crop_size, h - crop_size),
        ]

    elif pass_num == 2:
        # 4 edge midpoints (avoids corners and dead centre)
        cx, cy = (w - crop_size) // 2, (h - crop_size) // 2
        positions = [
            (cx, 0           ),   # top-centre
            (cx, h - crop_size),  # bottom-centre
            (0,  cy          ),   # left-middle
            (w - crop_size, cy),  # right-middle
        ]

    elif pass_num == 3:
        # 8 positions on a 3×3 grid, skipping dead centre
        xs = [0, (w - crop_size) // 2, w - crop_size]
        ys = [0, (h - crop_size) // 2, h - crop_size]
        positions = [
            (x, y) for x in xs for y in ys
            if not (x == xs[1] and y == ys[1])   # skip true centre
        ]

    else:
        # pass 4: 16 pseudo-random positions (deterministic per image)
        rng = random.Random(w * 1000 + h)   # seed from image dims
        positions = [
            (rng.randint(0, max(0, w - crop_size)),
             rng.randint(0, max(0, h - crop_size)))
            for _ in range(16)
        ]

    return [_safe_crop(x, y) for x, y in positions]


def _best_crop(candidates: list, std_threshold: float):
    """
    From a list of (crop_PIL, x, y), return the crop with the LOWEST std
    that is still >= std_threshold.  If none qualify, return the one with
    the lowest std overall (best available, with floor relaxed).
    Returns (crop_PIL, actual_std) or (None, 0) if candidates is empty.
    """
    if not candidates:
        return None, 0.0

    scored = []
    for crop, x, y in candidates:
        arr = np.array(crop).astype(float)
        scored.append((arr.std(), crop))

    scored.sort(key=lambda t: t[0])   # ascending: lowest std first

    # Prefer lowest std that still passes the threshold (not blank)
    for std_val, crop in scored:
        if std_val >= std_threshold:
            return crop, std_val

    # Nothing passed threshold: fall back to absolute lowest std above floor
    for std_val, crop in scored:
        if std_val >= MIN_STD_FLOOR:
            return crop, std_val

    return None, 0.0   # everything was blank / pure colour


def generate_no_defect(
    src_class_dirs: list,
    dst_dir:        Path,
    n_per_class:    int   = 500,
    crop_size:      int   = 128,
    std_threshold:  float = 10.0,
) -> int:
    """
    Generate No_Defect images using a 4-pass adaptive cropping strategy.

    For each source class:
      - Iterate through passes 1→4, trying to reach n_per_class
      - Each image contributes its LEAST-textured qualifying crop
      - Warping images (which have texture everywhere) will still
        contribute their cleanest region via passes 3 & 4

    Args:
        src_class_dirs : list of (class_name, Path) tuples
        dst_dir        : where to save No_Defect images
        n_per_class    : target crops per source class (500)
        crop_size      : pixel size (128)
        std_threshold  : preferred min std; relaxed automatically if needed

    Returns total images saved.
    """
    dst_dir.mkdir(parents=True, exist_ok=True)
    total_saved = 0

    for cls_name, src_path in src_class_dirs:
        print(f"\n  Generating {n_per_class} No_Defect crops from  '{cls_name}/' ...")

        img_files = [f for f in sorted(src_path.iterdir())
                     if f.suffix.lower() in IMG_EXTS]
        random.shuffle(img_files)

        # Pre-compute one best-crop per image across all 4 passes
        # so we can rank images and pick the cleanest ones first
        img_pool = []   # list of (std_val, img_path, crop_PIL)

        for img_path in img_files:
            try:
                img = Image.open(img_path).convert("RGB")
            except Exception:
                continue

            best_crop_pil = None
            best_std      = -1.0

            for pass_num in range(1, 5):
                candidates = _candidate_crops(img, crop_size, pass_num)
                crop_pil, std_val = _best_crop(candidates, std_threshold)
                if crop_pil is not None and std_val > best_std:
                    best_crop_pil = crop_pil
                    best_std      = std_val
                # Stop early if we found a good crop in an early pass
                if best_std >= std_threshold:
                    break

            if best_crop_pil is not None and best_std >= MIN_STD_FLOOR:
                img_pool.append((best_std, img_path, best_crop_pil))

        # Sort pool: lowest std first (cleanest / least defect-like)
        img_pool.sort(key=lambda t: t[0])

        saved         = 0
        used_stds     = []

        for std_val, img_path, crop_pil in img_pool:
            if saved >= n_per_class:
                break
            out_name = f"nd_{cls_name}_{img_path.stem}.jpg"
            crop_pil.save(str(dst_dir / out_name), quality=92)
            saved += 1
            used_stds.append(std_val)

        total_saved += saved

        # Diagnostics
        if used_stds:
            print(f"    Saved    : {saved} / {n_per_class} crops")
            print(f"    Std range: {min(used_stds):.1f} – {max(used_stds):.1f}  "
                  f"(mean {np.mean(used_stds):.1f})")
            below_thresh = sum(1 for s in used_stds if s < std_threshold)
            if below_thresh:
                print(f"    Note     : {below_thresh} crops used relaxed threshold "
                      f"(std < {std_threshold}) — Warping images have texture everywhere")
        else:
            print(f"    [WARN] No usable crops found for '{cls_name}'")

        if saved < n_per_class:
            shortfall = n_per_class - saved
            print(f"    [WARN] Short by {shortfall} images. "
                  f"Pool had only {len(img_pool)} qualifying images × 1 crop each.")
            print(f"           To fix: use --n_per_class {saved} or "
                  f"add more source images to '{cls_name}/'")

    print(f"\n  No_Defect total : {total_saved} images  →  {dst_dir}")
    return total_saved


