# 4.  DATASET STAGING
#     Creates: staging_dir/Cracking/  Stringing/  Warping/  No_Defect/
# ─────────────────────────────────────────────────────────────────────────────

def build_staged_dataset(
    data_dir:      str,
    staging_dir:   str,
    n_per_class:   int   = 500,
    crop_size:     int   = 128,
    std_threshold: float = 10.0,
) -> str:
    staging = Path(staging_dir)
    data    = Path(data_dir)

    if staging.exists():
        shutil.rmtree(str(staging))
    staging.mkdir(parents=True)

    def _find(name: str) -> Path:
        for d in data.iterdir():
            if d.is_dir() and d.name.lower() == name.lower():
                return d
        raise FileNotFoundError(
            f"Folder '{name}' not found in {data_dir}. "
            f"Available: {[d.name for d in data.iterdir() if d.is_dir()]}"
        )

    # ── Symlink / copy the 3 defect class folders ─────────────────────────────
    defect_dirs = []
    for cls in cfg.DEFECT_CLASSES:
        src = _find(cls)
        dst = staging / cls
        dst.mkdir()
        n = 0
        for img in sorted(src.iterdir()):
            if img.suffix.lower() in IMG_EXTS:
                try:
                    (dst / img.name).symlink_to(img.resolve())
                except (OSError, NotImplementedError):
                    shutil.copy2(str(img), str(dst / img.name))
                n += 1
        print(f"  Staged  {cls:<18}: {n:,} images")
        defect_dirs.append((cls, src))

    # ── Generate No_Defect ────────────────────────────────────────────────────
    print(f"\n  Generating No_Defect: {n_per_class} crops × "
          f"{len(defect_dirs)} classes = {n_per_class * len(defect_dirs)} images")
    generate_no_defect(
        src_class_dirs=defect_dirs,
        dst_dir=staging / "No_Defect",
        n_per_class=n_per_class,
        crop_size=crop_size,
        std_threshold=std_threshold,
    )

    print(f"\n  Staging complete  →  {staging_dir}")
    _print_counts(staging_dir)
    return staging_dir


def _print_counts(directory: str):
    print("\n  Class image counts:")
    for d in sorted(Path(directory).iterdir()):
        if d.is_dir():
            n = sum(1 for f in d.iterdir() if f.suffix.lower() in IMG_EXTS)
            print(f"    {d.name:<20}: {n:,} images")


