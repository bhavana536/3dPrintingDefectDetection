import cv2
print(cv2.__version__)

print("\n" + "=" * 55)
print("IMAGE PROPERTY ANALYSIS")
print("=" * 55)

heights, widths, channels_list = [], [], []

for p in all_image_paths[:300]:
    img = cv2.imread(str(p))
    if img is not None:
        h, w, c = img.shape
        heights.append(h)
        widths.append(w)
        channels_list.append(c)

print(f"  Width  — min: {min(widths)}, max: {max(widths)}, mean: {np.mean(widths):.1f}")
print(f"  Height — min: {min(heights)}, max: {max(heights)}, mean: {np.mean(heights):.1f}")
print(f"  All 3-channel (RGB): {all(c == 3 for c in channels_list)}")

print("\nComputing per-channel mean & std (sample of 500 images)...")

pixel_vals = {"R": [], "G": [], "B": []}
for p in all_image_paths[:500]:
    img = cv2.imread(str(p))
    if img is not None:
        img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB).astype(np.float32) / 255.0
        pixel_vals["R"].append(img_rgb[:,:,0].mean())
        pixel_vals["G"].append(img_rgb[:,:,1].mean())
        pixel_vals["B"].append(img_rgb[:,:,2].mean())

for ch, vals in pixel_vals.items():
    print(f"  Channel {ch} — mean: {np.mean(vals):.4f}, std: {np.std(vals):.4f}")

