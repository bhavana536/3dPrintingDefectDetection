IMG_SIZE = (128, 128)
BATCH_SIZE = 16

dataset = tf.keras.utils.image_dataset_from_directory(
    RAW_DIR,
    validation_split=0.2,
    subset="training",
    seed=42,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_names=["Cracking", "Stringing", "Warping"]  # only these
)

# ── Classes to IGNORE ───────────────────────────────────────
EXCLUDED_CLASSES = {"off_platform", "layer_shifting"}

# ── Classes to USE (from your study) ────────────────────────
VALID_CLASSES = {"Warping", "Stringing", "Cracking", "No_Defect"}

print("=" * 55)
print("DATASET DIRECTORY STRUCTURE")
print("=" * 55)

class_counts = {}
all_image_paths = []

for folder in sorted(RAW_DIR.rglob("*")):
    if folder.is_dir():
        # Skip excluded classes (case-insensitive check)
        if folder.name.lower() in {c.lower() for c in EXCLUDED_CLASSES}:
            print(f"  ⛔ SKIPPED  →  {folder.relative_to(RAW_DIR)}")
            continue

        images = list(folder.glob("*.jpg")) + \
                 list(folder.glob("*.jpeg")) + \
                 list(folder.glob("*.png"))

        if images:
            class_name = folder.name
            class_counts[class_name] = len(images)
            all_image_paths.extend(images)
            print(f"  ✅ {folder.relative_to(RAW_DIR)}  →  {len(images)} images")

print(f"\nTotal images (after exclusions) : {len(all_image_paths)}")
print(f"Classes used                     : {list(class_counts.keys())}")
print(f"Classes excluded                 : {EXCLUDED_CLASSES}")

fig, ax = plt.subplots(figsize=(8, 4))
bars = ax.bar(class_counts.keys(), class_counts.values(),
              color=["#e74c3c", "#3498db", "#2ecc71", "#f39c12"], edgecolor="black")
ax.set_title("Class Distribution — Warping / Stringing / Cracking / No_Defect", fontsize=12)
ax.set_xlabel("Defect Class")
ax.set_ylabel("Number of Images")
for bar, val in zip(bars, class_counts.values()):
    ax.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 10,
            str(val), ha="center", fontsize=10, fontweight="bold")
plt.tight_layout()
plt.savefig("class_distribution.png", dpi=150)
plt.show()

